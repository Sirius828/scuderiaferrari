# ======================== 执行测试 ========================
correct = 0
total = len(tests)
print(f"开始测试，总样本数：{total}\n")
errors = []

for idx, (text, expected) in enumerate(tests, 1):
    pred_label, conf = predict_direction_combined(text)
    pred_str = "右转" if pred_label == 1 else "直行"
    exp_str  = "右转" if expected == 1 else "直行"
    if pred_label == expected:
        correct += 1
    else:
        errors.append((text, exp_str, pred_str, conf))
        print(f"✗ [{idx}] 预期:{exp_str} 预测:{pred_str} | {text}")

print(f"\n========= 准确率: {correct}/{total} = {correct/total*100:.2f}% =========")
if errors:
    print(f"错误数量: {len(errors)}")
    with open("error_massive_test.txt", "w", encoding="utf-8") as f:
        for t, e, p, c in errors:
            f.write(f"预期:{e} 预测:{p} | {t}\n")
    print("错误详情已保存至 error_massive_test.txt")
else:
    print("🎉 全部正确！模型+规则完美！")